"""Константы и настройки модуля film_index.

Значения сгруппированы, чтобы правки политики сопоставления (пороги, веса,
дефолты) делались в одном месте.
"""

# --- Хронометраж -----------------------------------------------------------
# Oplan3.program.duration хранится в кадрах; для перевода длительности из
# каталога Кинопоиска (минуты) в кадры используем частоту кадров.
FPS = 25
DEFAULT_DURATION_MINUTES = 90
DEFAULT_DURATION_FRAMES = DEFAULT_DURATION_MINUTES * 60 * FPS

# --- Классификация материалов Oplan3 --------------------------------------
# Фильм/сериал определяем строго по program_type_id (program_kind содержит
# много сервисных типов и для классификации не годится).
FILM_TYPES = (5, 6, 10, 11)
SERIES_TYPES = (4, 12, 16)
ALLOWED_TYPES = FILM_TYPES + SERIES_TYPES

# program_kind (по факту данных Oplan3, см. docs/oplan3-identifiers.md):
#   0 - одиночный материал (фильм), родитель - папка-коллекция (kind=1);
#   1 - папка-коллекция ("Маня Поливанова", "Человек-паук" и т.п.);
#   3 - серия, parent_id указывает на родителя сезона (kind=4);
#   4 - родитель сезона/сериала ("#Ералаш"), родитель - папка (kind=1);
#   6 - служебные строки ("Вещательный" и пр.) - не материал.
EPISODE_KIND = 3
# Верхнеуровневые строки, которые сопоставляем с каталогом Кинопоиска:
# одиночные фильмы и родители сезонов. Папки-коллекции (kind=1) исключены.
MATCH_KINDS = (0, 4)
# Все строки, для которых строим film_material_index: фильмы и серии (у них
# свой has_file/duration) + родитель сезона (носитель kinopoisk_id). Папки
# (kind=1) и служебные (kind=6) исключены.
INDEX_KINDS = (0, 3, 4)

# --- Сопоставление ---------------------------------------------------------
# Веса сигналов. Режиссёр - полноценный параметр с весом, сопоставимым с
# названием: у одинаковых название+год часто расходятся именно режиссёры.
# Балл считается как средневзвешенное по ДОСТУПНЫМ сигналам (нет страны в
# Oplan -> делим на сумму весов title+year+director и т.д.).
WEIGHTS = {
    'title': 0.55,
    'year': 0.25,
    'country': 0.20,
    'director': 0.35,
}
# Второй шанс режиссёру, когда ФИО совпало не полностью (часть персон) или
# порядок имён не совпал: небольшой бонус к баллу режиссёра.
DIRECTOR_PARTIAL_BONUS = 0.10

# Авто-приём: только очень высокая уверенность + достаточный отрыв от второго
# кандидата. Всё остальное уходит на ручную проверку.
AUTO_HIGH_THRESHOLD = 0.85
REVIEW_BAND_THRESHOLD = 0.70
MARGIN = 0.10
YEAR_TOLERANCE = 1

# Тип материала: сначала кандидаты того же типа. Если лучший same-type ниже
# этого порога, разрешаем fallback на другой тип.
TYPE_FALLBACK_THRESHOLD = 0.70

# Кросс-тип можно auto-принять только при очень сильном совпадении.
CROSS_TYPE_AUTO = True
CROSS_TYPE_AUTO_THRESHOLD = 0.92
CROSS_TYPE_AUTO_TITLE = 0.98

# Oplan хранит русское название, если оно есть. Оригинальное название —
# вторичный сигнал и не должно перебивать хорошее русское совпадение.
ORIGINAL_TITLE_WEIGHT = 0.90
# Если у материала нет страны или года, авто-приём разрешаем только при
# практически точном совпадении названия.
TITLE_STRICT_FOR_AUTO = 0.95

DEFAULT_SAMPLE = 5000

# --- Бакеты результата -----------------------------------------------------
